package org.cassandragargoyle.portunix.vimparser.core;

import org.cassandragargoyle.portunix.vimparser.api.ExtractorPlugin;
import org.cassandragargoyle.portunix.vimparser.api.ParserPlugin;
import org.cassandragargoyle.portunix.vimparser.api.VisualizerPlugin;
import org.cassandragargoyle.portunix.vimparser.core.testsupport.TestExtractorPluginAlpha;
import org.cassandragargoyle.portunix.vimparser.core.testsupport.TestExtractorPluginBeta;
import org.cassandragargoyle.portunix.vimparser.core.testsupport.TestParserPluginStub;
import org.cassandragargoyle.portunix.vimparser.core.testsupport.TestVisualizerPluginStub;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Unit tests for PluginManager using test-only stub plugins registered as PF4J system extensions
 * via {@code @Extension} (META-INF/extensions.idx generated by the PF4J annotation processor at
 * test-compile time). Sibling plugin modules are not on the unit-test classpath; real-plugin
 * coverage lives in the {@code vim-parser-it} integration module.
 */
class PluginManagerTest
{
	private PluginManager manager;

	@BeforeEach
	void setUp()
	{
		manager = new PluginManager();
	}

	@AfterEach
	void tearDown()
	{
		manager.shutdown();
	}

	@Test
	void testDiscoverPlugins()
	{
		manager.discoverPlugins();

		List<ExtractorPlugin> extractors = manager.getExtractorPlugins();
		List<ParserPlugin> parsers = manager.getParserPlugins();
		List<VisualizerPlugin> visualizers = manager.getVisualizerPlugins();

		assertTrue(extractors.size() >= 2, "expected ≥2 stub extractors");
		assertTrue(parsers.size() >= 1, "expected ≥1 stub parser");
		assertTrue(visualizers.size() >= 1, "expected ≥1 stub visualizer");
	}

	@Test
	void testGetExtractorPlugin()
	{
		manager.discoverPlugins();

		ExtractorPlugin alpha = manager.getExtractorPlugin(TestExtractorPluginAlpha.ID);
		assertNotNull(alpha);
		assertEquals(TestExtractorPluginAlpha.ID, alpha.getId());

		ExtractorPlugin beta = manager.getExtractorPlugin(TestExtractorPluginBeta.ID);
		assertNotNull(beta);
		assertEquals(TestExtractorPluginBeta.ID, beta.getId());

		ExtractorPlugin nonexistent = manager.getExtractorPlugin("nonexistent");
		assertNull(nonexistent);
	}

	@Test
	void testGetParserPlugin()
	{
		manager.discoverPlugins();

		ParserPlugin parser = manager.getParserPlugin(TestParserPluginStub.ID);
		assertNotNull(parser);
		assertEquals(TestParserPluginStub.ID, parser.getId());
	}

	@Test
	void testGetVisualizerPlugin()
	{
		manager.discoverPlugins();

		VisualizerPlugin visualizer = manager.getVisualizerPlugin(TestVisualizerPluginStub.ID);
		assertNotNull(visualizer);
		assertEquals(TestVisualizerPluginStub.ID, visualizer.getId());
	}

	@Test
	void testExtractorsSortedByPriority()
	{
		manager.discoverPlugins();

		List<ExtractorPlugin> extractors = manager.getExtractorPlugins();

		for (int i = 1; i < extractors.size(); i++)
		{
			assertTrue(extractors.get(i - 1).getPriority() <= extractors.get(i).getPriority(),
				"Extractors should be sorted by priority");
		}
	}

	@Test
	void testGetExtractorPluginsFiltered()
	{
		manager.discoverPlugins();

		Set<String> filter = new HashSet<>();
		filter.add(TestExtractorPluginAlpha.ID);

		List<ExtractorPlugin> extractors = manager.getExtractorPlugins(filter);

		assertEquals(1, extractors.size());
		assertEquals(TestExtractorPluginAlpha.ID, extractors.get(0).getId());
	}

	@Test
	void testGetExtractorPluginsFilteredEmpty()
	{
		manager.discoverPlugins();

		List<ExtractorPlugin> all = manager.getExtractorPlugins(null);
		List<ExtractorPlugin> allEmpty = manager.getExtractorPlugins(new HashSet<>());

		assertEquals(all.size(), allEmpty.size());
	}

	@Test
	void testHasPlugin()
	{
		manager.discoverPlugins();

		assertTrue(manager.hasExtractorPlugin(TestExtractorPluginAlpha.ID));
		assertTrue(manager.hasExtractorPlugin(TestExtractorPluginBeta.ID));
		assertFalse(manager.hasExtractorPlugin("nonexistent"));

		assertTrue(manager.hasParserPlugin(TestParserPluginStub.ID));
		assertFalse(manager.hasParserPlugin("nonexistent"));

		assertTrue(manager.hasVisualizerPlugin(TestVisualizerPluginStub.ID));
		assertFalse(manager.hasVisualizerPlugin("nonexistent"));
	}

	@Test
	void testGetAllPluginIds()
	{
		manager.discoverPlugins();

		List<String> ids = manager.getAllPluginIds();

		assertTrue(ids.contains(TestExtractorPluginAlpha.ID));
		assertTrue(ids.contains(TestExtractorPluginBeta.ID));
		assertTrue(ids.contains(TestParserPluginStub.ID));
		assertTrue(ids.contains(TestVisualizerPluginStub.ID));
	}

	@Test
	void testShutdown()
	{
		manager.discoverPlugins();
		assertTrue(manager.hasExtractorPlugin(TestExtractorPluginAlpha.ID));

		manager.shutdown();

		assertFalse(manager.hasExtractorPlugin(TestExtractorPluginAlpha.ID));
	}

	@Test
	void testDiscoverPlugins_idempotent()
	{
		manager.discoverPlugins();
		int countBefore = manager.getExtractorPlugins().size();

		manager.discoverPlugins();
		int countAfter = manager.getExtractorPlugins().size();

		assertEquals(countBefore, countAfter);
	}

	@Test
	void testDefaultPluginsDir_besideJar(@TempDir Path dir) throws Exception
	{
		Path jar = Files.createFile(dir.resolve("vim-parser.jar"));
		Path plugins = Files.createDirectory(dir.resolve(PluginManager.PLUGINS_DIR_NAME));

		assertEquals(plugins.toAbsolutePath(), PluginManager.defaultPluginsDir(jar));
	}

	@Test
	void testDefaultPluginsDir_jarWithoutPluginsUsesWorkingDirectory(@TempDir Path dir) throws Exception
	{
		Path jar = Files.createFile(dir.resolve("vim-parser.jar"));

		assertEquals(Paths.get(PluginManager.PLUGINS_DIR_NAME), PluginManager.defaultPluginsDir(jar));
	}

	@Test
	void testDefaultPluginsDir_classesDirectoryUsesWorkingDirectory(@TempDir Path dir) throws Exception
	{
		// A classes directory (IDE, unit tests) keeps the relative plugins directory
		Files.createDirectory(dir.resolve(PluginManager.PLUGINS_DIR_NAME));

		assertEquals(Paths.get(PluginManager.PLUGINS_DIR_NAME), PluginManager.defaultPluginsDir(dir));
		assertEquals(Paths.get(PluginManager.PLUGINS_DIR_NAME), PluginManager.defaultPluginsDir(null));
	}

	@Test
	void testHasExtractionPlugins()
	{
		assertFalse(manager.hasExtractionPlugins(), "nothing is discovered before discoverPlugins");

		manager.discoverPlugins();

		assertTrue(manager.hasExtractionPlugins());
	}

	@Test
	void testDescribePluginSource_emptyDirectoryIsDevelopmentMode(@TempDir Path dir)
	{
		PluginManager empty = new PluginManager(dir);
		try
		{
			empty.discoverPlugins();

			assertTrue(empty.isDevelopment());
			assertTrue(empty.describePluginSource().contains(dir.toAbsolutePath().normalize().toString()));
		}
		finally
		{
			empty.shutdown();
		}
	}
}
